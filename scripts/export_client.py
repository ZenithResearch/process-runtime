"""Generate typed Python payloads and methods plus the wire schema and OpenAPI."""
from pathlib import Path
import json
from process_runtime.contracts import COMMANDS, QUERIES, RESOURCE_TEMPLATES, schema_bundle

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/process_runtime_client"

def title(value):
    return ''.join(part.title() for part in value.replace('.', '_').split('_'))

def generate():
    lines = ['# Generated by scripts/export_client.py; do not edit.', 'from __future__ import annotations',
             'from typing import Any, Literal, NotRequired, TypedDict', 'from .client import RuntimeClient', '']
    classes = []
    def annotation(schema, name):
        if 'const' in schema:
            return f'Literal[{schema["const"]!r}]'
        if 'enum' in schema:
            return 'Literal[' + ', '.join(repr(item) for item in schema['enum']) + ']'
        if 'oneOf' in schema:
            return ' | '.join(annotation(item, name+str(index)) for index, item in enumerate(schema['oneOf']))
        kind = schema.get('type')
        if kind == 'object' and 'properties' in schema:
            fields = []
            required = schema.get('required', [])
            for key, value in schema['properties'].items():
                item = annotation(value, name+title(key))
                if key not in required:
                    item = 'NotRequired[' + item + ']'
                fields.append(f'    {key}: {item}')
            classes.append('class ' + name + '(TypedDict):\n' + ('\n'.join(fields) if fields else '    pass') + '\n')
            return name
        if kind == 'object':
            return 'dict[str, ' + annotation(schema.get('additionalProperties', {}), name+'Value') + ']'
        if kind == 'array':
            return 'list[' + annotation(schema.get('items', {}), name+'Item') + ']'
        return {'string':'str','integer':'int','number':'int | float','boolean':'bool','null':'None'}.get(kind, 'Any')
    payloads = {operation: annotation(schema, title(operation)+'Payload') for operation,schema in {**COMMANDS,**QUERIES}.items()}
    lines.extend(classes)
    lines.append('class TypedRuntimeClient(RuntimeClient):')
    for operation in COMMANDS:
        lines.extend([f'    def {operation.replace(".", "_")}(self, *, request_id: str, resource: str, expected_version: int | None, payload: {payloads[operation]}, evidence: bytes | None = None) -> dict[str, Any]:',
                      f'        return self.execute({{"schema":"runtime.command.v1", "operation":{operation!r}, "request_id":request_id, "resource":resource, "expected_version":expected_version, "payload":payload}}, evidence)', ''])
    for operation in QUERIES:
        lines.extend([f'    def {operation.replace(".", "_")}(self, payload: {payloads[operation]}, *, evidence: bytes | None = None) -> dict[str, Any]:',
                      f'        return self.query({{"schema":"runtime.query.v1", "operation":{operation!r}, "payload":payload}}, evidence)', ''])
    (TARGET/'generated.py').write_text('\n'.join(lines)+'\n')
    (TARGET/"resource-templates-v1.json").write_text(json.dumps(RESOURCE_TEMPLATES, indent=2)+"\n")
    bundle = schema_bundle()
    (TARGET/'runtime-v1.schema.json').write_text(json.dumps(bundle, indent=2)+'\n')
    # OpenAPI describes the stable transport; the standalone bundle remains canonical.
    api = {'openapi':'3.1.0','info':{'title':'Process Runtime','version':'0.1.0'}, 'servers':[{'url':'http://127.0.0.1:8092'}],
           'paths':{}, 'components':{'schemas':{'RuntimeContract':{'$ref':'./runtime-v1.schema.json'}}}}
    for route,kind in (('commands','command'),('queries','query')):
        transport={'type':'object','additionalProperties':False,'required':['schema','request','authority_base64'],
                   'properties':{'schema':{'const':'runtime.transport.v1'},'request':{'$ref':'./runtime-v1.schema.json#/$defs/'+kind},
                                 'authority_base64':{'type':'string','description':'Receiver-native evidence bytes; no bearer authority or caller-selected key.'}}}
        api['paths']['/v1/'+route]={'post':{'operationId':route,'requestBody':{'required':True,'content':{'application/json':{'schema':transport}}},
            'responses':{'200':{'description':'Versioned result','content':{'application/json':{'schema':{'$ref':'./runtime-v1.schema.json#/$defs/'+('result' if kind=='command' else 'query_result')}}}},
                         '400':{'description':'Closed runtime.error.v1'},'401':{'description':'No verified authority'},'403':{'description':'Receiver authorization denied'},'409':{'description':'Version, replay, lease or outcome conflict'},'503':{'description':'Unavailable; exact mutation outcome may require reconciliation'}}}}
    (ROOT/'contracts/openapi-v1.json').write_text(json.dumps(api,indent=2)+'\n')

if __name__ == '__main__':
    generate()
